"""Generate a config variant that hardens the shared llama3 fallback.

    gateway-env/bin/python experiments/make_fallback_config.py --limit 2 --out experiments/litellm_config.fb-limit.yaml
    gateway-env/bin/python experiments/make_fallback_config.py --second-node --out experiments/litellm_config.fb-node2.yaml
    gateway-env/bin/python experiments/make_fallback_config.py --limit 2 --second-node --out ...fb-both.yaml
    gateway-env/bin/python experiments/make_fallback_config.py --pool --limit 2 --second-node --out ...  # on the dedicated-pool layout

  --limit N       max_parallel_requests=N on every fallback deployment (a router-level limit on
                  concurrent calls to that deployment)
  --second-node   add a second llama3 deployment (fallback-node-2, port 11439) to the fallback alias
  --standby N     replace the llama3 fallback with N phi3 deployments (fallback-node, -2, -3 on ports
                  11439..), i.e. fallback capacity comparable to the primaries when N = 3
  --cooldown S    router cooldown_time in seconds (default config: 30)
  --pool          start from the dedicated-pool config (experiments/make_pool_config.py)
"""
import argparse
from pathlib import Path

import yaml

ROOT = Path(__file__).parent.parent


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--limit", type=int, help="max_parallel_requests per fallback deployment")
    ap.add_argument("--second-node", action="store_true")
    ap.add_argument("--standby", type=int, help="N phi3 standby nodes instead of the llama3 fallback")
    ap.add_argument("--cooldown", type=int, help="router cooldown_time (s)")
    ap.add_argument("--pool", action="store_true")
    ap.add_argument("--out", required=True)
    args = ap.parse_args()

    base = ROOT / ("experiments/litellm_config.pool.yaml" if args.pool else "litellm_config.yaml")
    cfg = yaml.safe_load(base.read_text())
    cfg.pop("x-ollama-params", None)

    fallbacks = [m for m in cfg["model_list"] if m["model_name"] == "my-fallback-model"]
    assert len(fallbacks) == 1, "expected a single fallback deployment in the base config"
    if args.standby:
        template = fallbacks[0]
        cfg["model_list"].remove(template)
        fallbacks = []
        for i in range(args.standby):
            d = yaml.safe_load(yaml.safe_dump(template))  # deep copy
            d["litellm_params"]["model"] = "ollama/phi3"
            d["litellm_params"]["api_base"] = f"http://localhost:{11439 + i}"
            d["model_info"]["id"] = "fallback-node" if i == 0 else f"fallback-node-{i + 1}"
            cfg["model_list"].append(d)
            fallbacks.append(d)
    if args.second_node:
        second = yaml.safe_load(yaml.safe_dump(fallbacks[0]))  # deep copy
        second["litellm_params"]["api_base"] = "http://localhost:11439"
        second["model_info"]["id"] = "fallback-node-2"
        cfg["model_list"].insert(cfg["model_list"].index(fallbacks[0]) + 1, second)
        fallbacks.append(second)
    if args.limit:
        for m in fallbacks:
            m["litellm_params"]["max_parallel_requests"] = args.limit

    if args.cooldown:
        cfg["router_settings"]["cooldown_time"] = args.cooldown
    bits = [f"standby={args.standby}" if args.standby else None, f"cooldown={args.cooldown}s" if args.cooldown else None,
            f"limit={args.limit}" if args.limit else None, "second-node" if args.second_node else None, "pool" if args.pool else None]
    header = f"# GENERATED by experiments/make_fallback_config.py ({', '.join(b for b in bits if b) or 'no changes'}). Do not edit.\n"
    out = ROOT / args.out
    out.write_text(header + yaml.safe_dump(cfg, sort_keys=False, width=100))
    print(f"wrote {args.out}: fallback deployments {[m['model_info']['id'] for m in fallbacks]}"
          + (f", max_parallel_requests={args.limit}" if args.limit else "")
          + (f", cooldown_time={args.cooldown}" if args.cooldown else ""))


if __name__ == "__main__":
    main()
