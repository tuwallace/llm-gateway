"""Generate experiments/litellm_config.pool.yaml from litellm_config.yaml.

Reserves node-3 (port 11437) for the research team:
  - node-3 leaves `my-educational-model` and becomes `research-node`, reachable only
    through a new `research-model` alias
  - `research-model` falls back to `my-fallback-model`, exactly like the shared alias,
    so the failure phases of a simulation stay comparable with the baseline
  - both aliases are health-checked

    gateway-env/bin/python experiments/make_pool_config.py
    CONFIG=experiments/litellm_config.pool.yaml ./restart_gateway.sh --reset
"""
from pathlib import Path

import yaml

ROOT = Path(__file__).parent.parent
OUT = Path(__file__).parent / "litellm_config.pool.yaml"


def main() -> None:
    cfg = yaml.safe_load((ROOT / "litellm_config.yaml").read_text())
    cfg.pop("x-ollama-params", None)  # anchors are already expanded on load

    node3 = next(m for m in cfg["model_list"] if m["model_info"]["id"] == "node-3")
    node3["model_name"] = "research-model"
    node3["model_info"]["id"] = "research-node"

    cfg["router_settings"]["fallbacks"].append({"research-model": ["my-fallback-model"]})
    cfg["general_settings"]["background_health_check_model_groups"].append("research-model")

    header = ("# GENERATED by experiments/make_pool_config.py from litellm_config.yaml. Do not edit.\n"
              "# Dedicated pool: node-3 (11437) serves only `research-model`; the shared alias has node-1, node-2.\n")
    OUT.write_text(header + yaml.safe_dump(cfg, sort_keys=False, width=100))
    shared = [m["model_info"]["id"] for m in cfg["model_list"] if m["model_name"] == "my-educational-model"]
    print(f"wrote {OUT.relative_to(ROOT)}: shared pool {shared}, research pool ['research-node']")


if __name__ == "__main__":
    main()
